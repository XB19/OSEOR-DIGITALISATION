    CHANNEL_LAYERS = {
        "default": {
            # Variante pub/sub : abonnement persistant, robuste pour les
            # connexions WebSocket longue durée (pas de timeout de lecture).
            "BACKEND": "channels_redis.pubsub.RedisPubSubChannelLayer",
            "CONFIG": {"hosts": [REDIS_URL]},
        }
    }
